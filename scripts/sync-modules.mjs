// Copies the website fields of Pallume's module descriptions into content/.
// Master: ~/Overwatch/02-businesses/pallume/module-descriptions.json (Productization).
// Vercel can't read the master, so the site builds from this generated copy.
// Run `npm run sync:modules` after Productization changes the master, then commit.
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const master =
  process.env.PALLUME_MODULES ?? join(homedir(), "Overwatch/02-businesses/pallume/module-descriptions.json");
const out = new URL("../content/modules.generated.json", import.meta.url);

const { modules } = JSON.parse(readFileSync(master, "utf8"));
const site = modules.map(({ key, name, site }) => ({ key, name, site }));

writeFileSync(
  out,
  JSON.stringify(
    {
      _generated: "Do not edit. Generated by scripts/sync-modules.mjs from 02-businesses/pallume/module-descriptions.json.",
      modules: site,
    },
    null,
    2
  ) + "\n"
);
console.log(`synced ${site.length} modules`);
